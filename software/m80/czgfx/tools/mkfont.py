# name, glyph table, cell w, cell h, glyph w, stored rows, module, comment
FONTS = [
    ('CZF8', G8, 8, 8, 5, 7, 'CZFNT8',
     '8x8 cell, glyphs 5x7, the top row blank'),
    ('CZF11', G11, 9, 11, 7, 10, 'CZFN11',
     '9x11 cell, glyphs 7x10 (2 descender rows), the top row blank'),
]


def bottom_up(glyph):
    """The glyph's rows as bit masks, bottom row first, bit 0 = left."""
    out = []
    for r in reversed(glyph):
        out.append(sum(1 << x for x, c in enumerate(r) if c == '#'))
    return out


def pack(glyph, w):
    bits = []
    for row in bottom_up(glyph):
        bits += [(row >> x) & 1 for x in range(w)]
    while len(bits) % 8:
        bits.append(0)
    return [sum(bits[i + k] << k for k in range(8)) for i in range(0, len(bits), 8)]


def module(name, table, cw, ch, gw, gr, mod, comment):
    missing = [chr(c) for c in range(0x20, 0x7F) if chr(c) not in table]
    assert not missing, (name, missing)
    nb = (gw * gr + 7) // 8
    lines = [
        '; SPDX-License-Identifier: GPL-3.0-or-later',
        '; Copyright (C) 2026 Todd Houg',
        ';',
        f'; {mod}.MAC -- czgfx: the {name} text font, characters 20H-7EH',
        ';',
        f'; {comment}.',
        '; Generated by tools/mkfont.py (edit the glyphs there). See CZTXT.MAC',
        '; for the descriptor and the bit-packed glyph format.',
        ';',
        f'        PUBLIC  {name}',
        ';',
        '        CSEG',
        ';',
        f'{name}:' + ' ' * (8 - len(name) - 1) + f'DB      {cw},{ch},{gw},{gr},{nb}'
        + ' ' * 8 + ';cell w,h; glyph w, rows; bytes each',
    ]
    for c in range(0x20, 0x7F):
        ch_ = chr(c)
        b = pack(table[ch_], gw)
        assert len(b) == nb
        label = ch_ if ch_ not in "';" else repr(ch_)
        lines.append('        DB      ' + ','.join(f'0{v:02X}H' for v in b)
                     + f'   ;{c:02X} {label}')
    lines += [';', '        END', '']
    return '\n'.join(lines)


def preview(path):
    from PIL import Image
    imgs = []
    for name, table, cw, ch, gw, gr, mod, _ in FONTS:
        cols = 16
        img = Image.new('L', (cols * cw, 6 * ch), 0)
        for i, c in enumerate(range(0x20, 0x7F)):
            ox, oy = (i % cols) * cw, (i // cols) * ch
            for r, row in enumerate(bottom_up(table[chr(c)])):
                for x in range(gw):
                    if (row >> x) & 1:
                        img.putpixel((ox + x, oy + ch - 1 - r), 255)
        imgs.append(img.resize((img.width * 4, img.height * 4), Image.NEAREST))
    out = Image.new('L', (max(i.width for i in imgs), sum(i.height + 16 for i in imgs)), 40)
    y = 0
    for i in imgs:
        out.paste(i, (0, y))
        y += i.height + 16
    out.save(path)


def main():
    if len(sys.argv) == 3 and sys.argv[1] == '--preview':
        preview(sys.argv[2])
        return
    src = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src')
    for f in FONTS:
        with open(os.path.join(src, f[6] + '.MAC'), 'w') as fh:
            fh.write(module(*f))


if __name__ == '__main__':
    main()
