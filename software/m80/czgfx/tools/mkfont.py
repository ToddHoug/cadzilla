"""Generate czgfx's text fonts: src/CZFNT8.MAC (CZF8) and src/CZFN11.MAC (CZF11).

Both fonts cover characters 20H-7EH. A glyph is stored bit-packed: its rows
bottom-up, each row its W columns as W bits, left column first, and the bits
packed into bytes least significant bit first. Unpacked, a row is a row of the
ACRTC's pattern RAM as it is (bit 0 = the leftmost pixel, row 0 the bottom),
which CZTXT.MAC loads and draws with PTN. Rows above the stored ones, and the
columns right of the glyph, are blank: the character cell's spacing.

  CZF8   8x8 cell: glyphs 5 wide, 7 rows (lower-case descenders inside them),
         the top row blank. 35 bits = 5 bytes a character (475 bytes).
         The same pixels as CZBASIC's original font.
  CZF11  9x11 cell: glyphs 7 wide, 10 rows (2 descender rows, then 8 rows
         of capitals), the top row blank. 70 bits = 9 bytes (855 bytes).

A font module starts with its descriptor:
    DB  cell width, cell height, glyph width, stored rows, bytes a character
then the 95 glyphs.

Usage:
  python3 tools/mkfont.py                 write src/CZFNT8.MAC, src/CZFN11.MAC
  python3 tools/mkfont.py --preview F.png render both fonts to a PNG (needs PIL)
then tools/altairsim/scripts/crlf.sh on the two .MAC files.
"""
