# Writes src/RFTAB.INC, ROCKFALL's lookup tables, so the 8080 does no
# trigonometry: the per-heading vectors (thrust, shot speeds, unit
# directions, the ship's nose), the ship and flame outlines for every
# heading, the rock outlines (random, from a fixed seed), the raider, the
# life icon and the arctangent table the raider aims with. Run from
# anywhere:
#   python3 software/z88dk/rockfall/tools/mktables.py
import math
import os
import random

HEADS = 32                  # headings: 0 points up, each step 11.25 deg CCW
AIMS = 128                  # raider aim directions, finer: 2.8 deg a step

# speeds, 8.8 fixed point (256 = one pixel a frame)
THRUST = 0.30 * 256         # ship acceleration per frame of thrust
SHOT = 12.0 * 256           # player shot speed
RSHOT = 7.0 * 256           # raider shot speed
UNIT = 64                   # DIRV length: rock/debris speed k = k/4 px a frame
NOSE = 15                   # shots start this far ahead of the centre

SHIP = [(0, 14), (9, -9), (0, -4), (-9, -9)]
FLAME = [(-4, -7), (0, -17), (4, -7)]
RAIDER = [(-20, 0), (-10, -7), (10, -7), (20, 0), (10, 5), (6, 5),
          (3, 11), (-3, 11), (-6, 5), (-10, 5)]
LIFE = [(0, 10), (6, -6), (0, -3), (-6, -6)]

out = []


def dw(label, words, per=8):
    first = True
    for i in range(0, len(words), per):
        chunk = ",".join(str(w) for w in words[i:i + per])
        out.append(("%-8sDW      %s" % ((label + ":") if first and label else "", chunk)))
        first = False


def db(label, vals, per=16):
    first = True
    for i in range(0, len(vals), per):
        chunk = ",".join(str(v) for v in vals[i:i + per])
        out.append(("%-8sDB      %s" % ((label + ":") if first and label else "", chunk)))
        first = False


def vec(h, length, steps=HEADS):
    a = math.radians(90.0 + 360.0 * h / steps)
    return [round(length * math.cos(a)), round(length * math.sin(a))]


def rot(pts, h):
    a = math.radians(360.0 * h / HEADS)
    c, s = math.cos(a), math.sin(a)
    return [(round(x * c - y * s), round(x * s + y * c)) for x, y in pts]


def shape(label, pts):
    """An RPLG shape: DB n (deltas), DW the first vertex from the centre,
    then the n deltas as the ACRTC takes them, high byte first (DB), for
    FSEND. RPLG closes the polygon back to the first vertex."""
    out.append("%-8sDB      %d" % (label + ":", len(pts) - 1))
    dw("", [pts[0][0], pts[0][1]])
    bytes_ = []
    for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
        for v in (x1 - x0, y1 - y0):
            v &= 0xFFFF
            bytes_ += ["%03XH" % (v >> 8), "%03XH" % (v & 0xFF)]
    db("", bytes_)


def rock(rng, n, r, jit):
    pts = []
    for i in range(n):
        a = 2 * math.pi * (i + rng.uniform(-0.3, 0.3)) / n
        rr = r + rng.uniform(-jit, jit)
        pts.append((round(rr * math.cos(a)), round(rr * math.sin(a))))
    return pts


out.append("; SPDX-License-Identifier: GPL-3.0-or-later")
out.append("; Copyright (C) 2026 Todd Houg")
out.append(";")
out.append("; RFTAB.INC -- ROCKFALL's lookup tables. Generated by tools/mktables.py;")
out.append("; edit that, not this.")
out.append(";")
out.append("; Per heading h (0 up, +1 = 11.25 deg CCW), X,Y word pairs:")
out.append("; THRV thrust and SHOTV shot velocities (8.8), DIRV unit")
out.append("; directions (length %d), NOSEV the ship's nose (pixels)." % UNIT)
for name, length in (("THRV", THRUST), ("SHOTV", SHOT),
                     ("DIRV", UNIT), ("NOSEV", NOSE)):
    words = []
    for h in range(HEADS):
        words += vec(h, length)
    dw(name, words)
out.append(";")
out.append("; RSHV: raider shot velocities (8.8) for %d aim directions, 0 up," % AIMS)
out.append("; counter-clockwise")
words = []
for h in range(AIMS):
    words += vec(h, RSHOT, AIMS)
dw("RSHV", words)
out.append(";")
out.append("; ATN64: atan(r/64) for r = 0..64, in aim steps (%g deg)" % (360.0 / AIMS))
db("ATN64", [round(math.degrees(math.atan(r / 64.0)) / (360.0 / AIMS))
             for r in range(65)])
out.append(";")
out.append("; EFFT: how far a coasting ship goes in t frames, t = 0..60, in frames")
out.append("; of its present speed (friction takes 1/64 a frame): 64(1-(63/64)^t)")
db("EFFT", [round(64 * (1 - (63 / 64) ** t)) for t in range(61)])
out.append(";")
out.append("; Shapes: DB n, DW the first vertex X,Y from the centre, then n")
out.append("; X,Y deltas, each high byte first (an RPLG polygon, closed back")
out.append("; to the first vertex).")
dw("SHIPT", ["SHIP%d" % h for h in range(HEADS)])
dw("FLAMET", ["FLAM%d" % h for h in range(HEADS)])
for h in range(HEADS):
    shape("SHIP%d" % h, rot(SHIP, h))
for h in range(HEADS):
    shape("FLAM%d" % h, rot(FLAME, h))
rng = random.Random(1979)
dw("ROCKLT", ["ROCKL%d" % i for i in range(4)])
dw("ROCKST", ["ROCKS%d" % i for i in range(4)])
for i in range(4):
    shape("ROCKL%d" % i, rock(rng, 11, 36, 9))
for i in range(4):
    shape("ROCKS%d" % i, rock(rng, 7, 13, 4))
dw("ROCKMT", ["ROCKM%d" % i for i in range(4)])
for i in range(4):
    shape("ROCKM%d" % i, rock(rng, 9, 22, 6))
shape("RAIDS", RAIDER)
shape("LIFEIC", LIFE)

path = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                    "..", "src", "RFTAB.INC")
with open(path, "w") as f:
    f.write("\n".join(out) + "\n")
print("wrote", os.path.normpath(path))
