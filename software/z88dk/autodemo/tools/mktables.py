# Writes src/ADTAB.INC, AUTODEMO's lookup tables, so the 8080 does no
# trigonometry: the ellipse morph wave, the palette colour wheel, the
# rotated polygons (absolute screen points, ready for CZPLG) and the radar
# rays. Run from anywhere:
#   python3 software/z88dk/autodemo/tools/mktables.py
import math
import os

CX, CY = 512, 384           # screen centre (1024x768)
STEPS = 48                  # rotation steps per polygon cycle
STRIDE = 13                 # words per polygon entry: DW n + 6 points

out = []


def dw(label, words, per=8):
    first = True
    for i in range(0, len(words), per):
        chunk = ",".join(str(w) for w in words[i:i + per])
        out.append(("%-8sDW      %s" % (label + ":" if first else "", chunk)))
        first = False


def db(label, vals, per=16):
    first = True
    for i in range(0, len(vals), per):
        chunk = ",".join(str(v) for v in vals[i:i + per])
        out.append(("%-8sDB      %s" % (label + ":" if first else "", chunk)))
        first = False


out.append("; SPDX-License-Identifier: GPL-3.0-or-later")
out.append("; Copyright (C) 2026 Todd Houg")
out.append(";")
out.append("; ADTAB.INC -- AUTODEMO's lookup tables. Generated by tools/mktables.py;")
out.append("; edit that, not this.")
out.append(";")

# WAVE: 64-entry triangle wave, -12..+12 (the ellipse morph)
wave = []
for n in range(64):
    if n < 16:
        v = 12 * n / 16
    elif n < 48:
        v = 12 * (1 - (n - 16) / 16)
    else:
        v = -12 + 12 * (n - 48) / 16
    wave.append(int(round(v)))
out.append("; ellipse morph: 64-step triangle wave, -12..+12 pixels")
db("WAVE", wave)
out.append(";")

# WHEEL: 48 hues of an RGB colour wheel, twice over, so any 32 in a row
# are contiguous without wrapping
wheel = []
for h in range(48):
    seg, f = divmod(h, 8)
    f *= 36
    r, g, b = [(255, f, 0), (255 - f, 255, 0), (0, 255, f),
               (0, 255 - f, 255), (f, 0, 255), (255, 0, 255 - f)][seg]
    wheel += [r, g, b]
out.append("; palette colour wheel: 48 R,G,B triples, twice")
db("WHEEL", wheel * 2, 12)
out.append(";")


def polygon(n, r, direction):
    words = []
    for i in range(STEPS):
        t0 = direction * i * (2 * math.pi / n) / STEPS + math.pi / 2
        pts = []
        for k in range(n):
            t = t0 + k * 2 * math.pi / n
            x = int(round(CX + r * math.cos(t)))
            y = int(round(CY + r * math.sin(t)))
            assert 0 <= x <= 1023 and 0 <= y <= 767
            pts += [x, y]
        entry = [n] + pts
        entry += [0] * (STRIDE - len(entry))
        words += entry
    return words


for label, n, r, d in (("PSQ", 4, 360, 1), ("PHEX", 6, 270, -1),
                       ("PTRI", 3, 160, 1)):
    out.append("; %s: %d-gon, radius %d, %d steps of one %d-fold turn, %s"
               % (label, n, r, STEPS, n, "CCW" if d > 0 else "CW"))
    dw(label, polygon(n, r, d), STRIDE)
    out.append(";")

# RAYS: 256 radar ray end points (the other end is the centre)
rays = []
for i in range(256):
    t = 2 * math.pi * i / 256
    rays += [int(round(CX + 360 * math.cos(t))), int(round(CY + 360 * math.sin(t)))]
out.append("; radar rays: 256 end points, radius 360, CCW from east")
dw("RAYS", rays, 8)

path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "ADTAB.INC")
with open(path, "w") as f:
    f.write("\n".join(out) + "\n")
print("wrote", os.path.normpath(path), len(out), "lines")
