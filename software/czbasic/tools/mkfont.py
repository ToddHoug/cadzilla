    print('; character is 5 bytes, its columns left to right; bit r of a')
    print('; column is pattern row r, row 0 the bottom (CZTEXT makes rows).')
    print(';')
    print('        PUBLIC  FONT')
    print(';')
    print('        CSEG')
    print(';')
    print('FONT:')
    for c in range(0x20, 0x7F):
        ch = chr(c)
        b = cell(ch)
        name = ch if ch not in "';" else repr(ch)
        print('        DB      ' + ','.join(f'0{v:02X}H' for v in b)
              + f'   ;{c:02X} {name}')
    print(';')
    print('        END')


