def rows(ch):
    """8 row bytes, pattern row 0 (the bottom) first, bit 0 = leftmost."""
    rows = list(G[ch])
    rows = ['.....'] + rows            # 8 rows: a blank top row
    out = []
    for r in reversed(rows):           # bottom row first
        b = 0
        for x, c in enumerate(r):      # glyph column x -> bit x
            if c == '#':
                b |= 1 << x
        out.append(b)
    return out


def cell(ch):
    """5 column bytes, leftmost first, bit r = pattern row r."""
    rs = rows(ch)
    return [sum(((rs[r] >> c) & 1) << r for r in range(8)) for c in range(5)]


def main():
    missing = [chr(c) for c in range(0x20, 0x7F) if chr(c) not in G]
    assert not missing, missing
